CREATE OR REPLACE FUNCTION "public"."handle_auto_match_notification"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'pg_catalog', 'pg_temp'
    AS $$
DECLARE
    v_owner_user_id UUID;
    v_lost_pet_name TEXT;
    v_found_location TEXT;
    v_found_image_url TEXT;
    v_found_breed TEXT;
    v_score_percentage TEXT;
BEGIN
    IF NEW.similarity_score >= 0.70 THEN
        SELECT user_id, pet_name
        INTO v_owner_user_id, v_lost_pet_name
        FROM public.pet_lost_alerts
        WHERE id = NEW.lost_pet_id;

        SELECT found_location, image_url, breed
        INTO v_found_location, v_found_image_url, v_found_breed
        FROM public.pet_found_alerts
        WHERE id = NEW.found_pet_id;

        IF v_owner_user_id IS NOT NULL THEN
            v_score_percentage :=
                TO_CHAR(
                    ROUND((NEW.similarity_score * 100)::NUMERIC, 1),
                    'FM990.0'
                ) || '%';

            INSERT INTO public.notifications (
                user_id,
                type,
                title,
                body,
                is_read,
                related_pet_id,
                related_match_id,
                metadata,
                created_at
            )
            VALUES (
                v_owner_user_id,
                'match_found',
                'Possível correspondência encontrada! (' ||
                    v_score_percentage || ')',
                'Um pet com características visuais semelhantes a "' ||
                    COALESCE(v_lost_pet_name, 'seu pet') ||
                    '" foi avistado em ' ||
                    COALESCE(v_found_location, 'sua região') ||
                    '. Toque para conferir.',
                FALSE,
                NEW.lost_pet_id,
                NEW.found_pet_id,
                jsonb_build_object(
                    'match_id', NEW.id,
                    'similarity_score', NEW.similarity_score,
                    'lost_pet_id', NEW.lost_pet_id,
                    'found_pet_id', NEW.found_pet_id,
                    'found_pet_image_url', v_found_image_url,
                    'found_pet_breed', v_found_breed
                ),
                NOW()
            )
            ON CONFLICT (
                user_id,
                related_pet_id,
                related_match_id
            )
            WHERE type = 'match_found'
              AND related_pet_id IS NOT NULL
              AND related_match_id IS NOT NULL
            DO NOTHING;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;


ALTER FUNCTION "public"."handle_auto_match_notification"() OWNER TO "postgres";


